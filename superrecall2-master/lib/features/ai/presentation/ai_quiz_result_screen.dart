import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../state/ai_quiz_controller.dart';
import 'ai_explanation_area.dart';
import '../../study/domain/learning_models.dart';


class AiQuizResultScreen extends StatefulWidget {
  const AiQuizResultScreen({super.key});

  @override
  State<AiQuizResultScreen> createState() => _AiQuizResultScreenState();
}

class _AiQuizResultScreenState extends State<AiQuizResultScreen> {
  final Map<String, String> _selectedOptions = {};
  bool _submitted = false;

  int get _correctCount {
    final quiz = context.read<AiQuizController>().generatedQuiz;
    if (quiz == null) return 0;
    var score = 0;
    for (final question in quiz.questions) {
      final correct = question.correctOption;
      if (correct != null && _selectedOptions[question.id] == correct.label) {
        score++;
      }
    }
    return score;
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final controller = context.watch<AiQuizController>();
    final quiz = controller.generatedQuiz;

    if (quiz == null) {
      return Scaffold(
        appBar: AppBar(),
        body: const Center(child: Text('No quiz generated')),
      );
    }

    return Scaffold(
      appBar: AppBar(
        title: Text(quiz.title),
        actions: [
          IconButton(
            onPressed: () => controller.reset(),
            icon: const Icon(Icons.refresh_rounded),
            tooltip: 'Generate New',
          ),
        ],
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(20),
        child: Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 840),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Container(
                  padding: const EdgeInsets.all(24),
                  decoration: BoxDecoration(
                    gradient: const LinearGradient(
                      colors: [Color(0xFF0F766E), Color(0xFF16302B)],
                    ),
                    borderRadius: BorderRadius.circular(24),
                  ),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Row(
                        children: [
                          const Icon(Icons.auto_awesome_rounded, color: Colors.white, size: 20),
                          const SizedBox(width: 8),
                          Text(
                            'AI GENERATED PRACTICE',
                            style: theme.textTheme.labelLarge?.copyWith(
                              color: Colors.white.withValues(alpha: 0.8),
                              letterSpacing: 1.1,
                            ),
                          ),
                        ],
                      ),
                      const SizedBox(height: 12),
                      Text(
                        quiz.title,
                        style: theme.textTheme.headlineSmall?.copyWith(color: Colors.white),
                      ),
                      const SizedBox(height: 8),
                      Text(
                        'This quiz was dynamically generated by Gemini to test your understanding of ${quiz.title}.',
                        style: theme.textTheme.bodyMedium?.copyWith(color: Colors.white70),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: 24),
                for (var i = 0; i < quiz.questions.length; i++)
                  Padding(
                    padding: const EdgeInsets.only(bottom: 20),
                    child: _AiQuizQuestionCard(
                      index: i + 1,
                      question: quiz.questions[i],
                      selectedLabel: _selectedOptions[quiz.questions[i].id],
                      submitted: _submitted,
                      onOptionSelected: (label) {
                        if (_submitted) return;
                        setState(() {
                          _selectedOptions[quiz.questions[i].id] = label;
                        });
                      },
                    ),
                  ),
                if (!_submitted)
                  SizedBox(
                    width: double.infinity,
                    child: FilledButton(
                      onPressed: _selectedOptions.length == quiz.questions.length
                          ? () => setState(() => _submitted = true)
                          : null,
                      style: FilledButton.styleFrom(
                        padding: const EdgeInsets.all(20),
                        backgroundColor: const Color(0xFF0F766E),
                      ),
                      child: const Text('Complete Practice'),
                    ),
                  )
                else
                  Container(
                    padding: const EdgeInsets.all(24),
                    decoration: BoxDecoration(
                      color: const Color(0xFFE8F3F1),
                      borderRadius: BorderRadius.circular(24),
                    ),
                    child: Column(
                      children: [
                        Text(
                          'Practice Complete!',
                          style: theme.textTheme.titleLarge?.copyWith(color: const Color(0xFF0F766E)),
                        ),
                        const SizedBox(height: 8),
                        Text(
                          'Score: $_correctCount / ${quiz.questions.length}',
                          style: theme.textTheme.displaySmall?.copyWith(color: const Color(0xFF0F766E)),
                        ),
                        const SizedBox(height: 24),
                        OutlinedButton(
                          onPressed: () {
                            controller.reset();
                            Navigator.pop(context);
                          },
                          child: const Text('Return to Study Plan'),
                        ),
                      ],
                    ),
                  ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}

class _AiQuizQuestionCard extends StatelessWidget {
  const _AiQuizQuestionCard({
    required this.index,
    required this.question,
    required this.selectedLabel,
    required this.submitted,
    required this.onOptionSelected,
  });

  final int index;
  final QuizQuestion question;
  final String? selectedLabel;
  final bool submitted;
  final ValueChanged<String> onOptionSelected;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);

    return Container(
      padding: const EdgeInsets.all(20),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(24),
        border: Border.all(color: const Color(0xFFE6D9C3)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text(
                'Question $index',
                style: theme.textTheme.titleMedium?.copyWith(color: const Color(0xFF0F766E)),
              ),
              if (submitted)
                Icon(
                  selectedLabel == question.correctOption?.label
                      ? Icons.check_circle_rounded
                      : Icons.error_rounded,
                  color: selectedLabel == question.correctOption?.label
                      ? Colors.green
                      : Colors.red,
                ),
            ],
          ),
          const SizedBox(height: 16),
          for (final block in question.promptBlocks)
            Padding(
              padding: const EdgeInsets.only(bottom: 12),
              child: Text(block.content, style: theme.textTheme.bodyLarge),
            ),
          const SizedBox(height: 8),
          for (final option in question.options)
            Padding(
              padding: const EdgeInsets.only(bottom: 10),
              child: InkWell(
                onTap: submitted ? null : () => onOptionSelected(option.label),
                borderRadius: BorderRadius.circular(16),
                child: Container(
                  padding: const EdgeInsets.all(14),
                  decoration: BoxDecoration(
                    color: _optionColor(option, selectedLabel, submitted),
                    borderRadius: BorderRadius.circular(16),
                    border: Border.all(
                      color: selectedLabel == option.label
                          ? const Color(0xFF0F766E)
                          : const Color(0xFFE2E8F0),
                    ),
                  ),
                  child: Row(
                    children: [
                      Text(
                        option.label,
                        style: TextStyle(
                          fontWeight: FontWeight.bold,
                          color: selectedLabel == option.label
                              ? const Color(0xFF0F766E)
                              : Colors.black54,
                        ),
                      ),
                      const SizedBox(width: 12),
                      Expanded(child: Text(option.value)),
                    ],
                  ),
                ),
              ),
            ),
          if (submitted) AiExplanationArea(question: question),
        ],
      ),
    );
  }

  Color _optionColor(QuestionOption option, String? selected, bool submitted) {
    if (!submitted) {
      return selected == option.label ? const Color(0xFFE8F3F1) : Colors.white;
    }
    if (option.status == QuestionOptionStatus.correct) {
      return const Color(0xFFDCFCE7);
    }
    if (selected == option.label) {
      return const Color(0xFFFEE2E2);
    }
    return Colors.white;
  }
}
